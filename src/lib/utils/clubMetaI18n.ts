/**
 * "원" 통화 단위를 언어별로 치환. 숫자 앞에 통화 기호 붙임.
 *   "15,000원" → "₩15,000" (모든 외국어 공통, 원화 기호가 국제 표준)
 *   "15,000원~" → "₩15,000+"
 */
function replaceCurrency(s: string, lang: Lang): string {
  if (lang === "ko") return s;
  // "숫자,숫자원~" → "₩숫자+"
  return s
    .replace(/(\d[\d,]*)원~/g, "₩$1+")
    .replace(/(\d[\d,]*)원/g, "₩$1");
}

