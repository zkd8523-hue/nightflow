/**
 * 공연(club_events) 전용 광역 지역 분류.
 *
 * 배경: AREA_OPTIONS(clubs/tags.ts)는 "클럽이 있는 서울 동네"용 목록이라
 * 강남·홍대·이태원처럼 구 단위다. 클럽은 한 곳에 고정이라 이 세밀함이 맞는데,
 * 공연(콘서트·페스티벌)은 포스터마다 장소가 다르고 "서울"·"인천"처럼 시 단위로도
 * 찍히고 "타이페이"·"도쿄" 같은 해외 도시도 나온다.
 *
 * 실측(2026-08-30, 승인 공연 499건 중 지역 있는 것): 강남·홍대·이태원(구 단위) +
 * 서울·인천·부산·대구·대전·광주·제주(시 단위) + 타이페이·도쿄·홍콩(해외) 가 섞여 있다.
 * AREA_OPTIONS로 거르면 "서울"·"인천"이 통째로 빠지고 해외는 걸러낼 칩 자체가 없다.
 *
 * 그래서 공연 탭은 광역 단위로 다시 묶는다: 서울 시내 구 단위는 전부 "수도권"으로
 * 합치고, 나머지는 도시 단위 그대로, 해외는 "해외" 하나로 묶는다.
 *
 * ⚠️ 새 도시가 수집되면(부천·울산 등) 아래 매핑에 추가해야 그 공연이 지역 칩에
 *    잡힌다 — 안 넣으면 eventRegionOf가 null을 반환해 "전체"에서만 보인다
 *    (조용히 사라지지 않는다. 단 개별 지역 칩으로는 못 찾는다).
 */

export const EVENT_REGIONS = ["수도권", "부산", "대구", "대전", "광주", "제주", "해외"] as const;
export type EventRegion = (typeof EVENT_REGIONS)[number];

const REGION_MAP: Record<string, EventRegion> = {
  // 수도권 — 서울 구 단위 + 서울/인천/경기 시 단위
  서울: "수도권",
  강남: "수도권",
  홍대: "수도권",
  이태원: "수도권",
  건대: "수도권",
  잠실: "수도권",
  인천: "수도권",
  경기: "수도권",
  수원: "수도권",
  고양: "수도권",

  부산: "부산",
  대구: "대구",
  대전: "대전",
  광주: "광주",
  제주: "제주",

  // 해외
  타이페이: "해외",
  도쿄: "해외",
  홍콩: "해외",
  오사카: "해외",
};

/** 원문 venue_area → 공연 탭 지역 칩. 매핑에 없으면 null(칩엔 안 잡히지만 "전체"엔 남는다). */
export function eventRegionOf(rawArea: string | null | undefined): EventRegion | null {
  if (!rawArea) return null;
  return REGION_MAP[rawArea.trim()] ?? null;
}
