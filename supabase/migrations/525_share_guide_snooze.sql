-- Migration 525: 조각 가이드 "한 달간 보지 않기"
-- 날짜: 2026-08-05
-- 배경:
--   523의 share_guide_seen은 봤다/안 봤다 두 값뿐이라, 지금 당장 볼 생각이 없는
--   파트너에게는 매번 다시 뜨거나(나중에) 영영 안 뜨거나(닫기) 둘 중 하나였다.
--
--   흐름을 바꾼다: 큰 가이드를 바로 띄우지 않고 한 줄짜리 안내를 먼저 보여준다.
--     · 나중에         → 이번만 닫음 (다음 방문에 다시)
--     · 더보기         → 전체 가이드 → 닫으면 share_guide_seen = true (끝)
--     · 한 달간 보지 않기 → snoozed_until = now + 30일
--
--   기간을 두는 이유: 조각 개편은 한 번 읽으면 되는 공지라 영구 차단까지는 과하고,
--   매번 뜨면 성가시다. 한 달이면 다음 시즌에 한 번 더 눈에 띈다.
-- ============================================================================

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS share_guide_snoozed_until TIMESTAMPTZ;

COMMENT ON COLUMN users.share_guide_snoozed_until IS
  '조각 가이드 다시 보지 않기 만료 시각. NULL이면 제한 없음. Migration 525';
