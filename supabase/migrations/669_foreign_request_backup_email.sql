-- Migration 669: foreign_requests에 예비 연락처(이메일) 추가
--
-- 배경(2026-09-19): 야후재팬 검색으로 들어온 일본 손님이 48분간 클럽을 비교하고
-- ₩100만 예약을 제출했는데, 연락처가 LINE ID 하나뿐이었고 그 ID가 검색되지 않아
-- 연락 자체를 못 해서 예약을 놓쳤다.
--
-- LINE은 상대가 "ID로 친구 추가 허용"을 꺼두면 검색이 안 되고(일본 사용자는 기본
-- 차단이 흔하다), 한국 계정은 연령 인증 전이면 ID 검색 기능 자체가 막힌다.
-- 인스타·카카오도 같은 종류의 실패가 가능하다 — 연락 수단이 하나면 그게 막히는
-- 순간 리드가 통째로 증발한다.
--
-- 그래서 메신저와 별개로 이메일을 항상 받는다. 이메일은 상대 설정에 막히지 않는다.
--
-- NOT NULL로 걸지 않는다 — 기존 7건에 값이 없고, 백필할 방법도 없다.
-- 필수 여부는 폼에서 강제한다(신규 접수는 항상 채워져 들어온다).
-- ============================================================================

ALTER TABLE foreign_requests
  ADD COLUMN IF NOT EXISTS backup_email TEXT;

COMMENT ON COLUMN foreign_requests.backup_email IS
  '예비 연락처. 메신저(LINE·인스타 등) ID 검색이 막혀 연락 불가한 경우의 대체 경로. 폼에서 필수(Migration 669).';
